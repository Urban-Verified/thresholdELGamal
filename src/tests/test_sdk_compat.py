@pytest.mark.parametrize("kid", [1, 2, 3])
def test_verify_existing_fixture(kid: int):
    """Our verifier must accept the bytes the SDK already accepts."""
    fix = _load_fixture(f"thresholdElGamal_dkg_keyper_{kid}")
