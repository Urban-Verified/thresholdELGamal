def _setup_one_keyper():
    """Build a (mpk_k, msk_k, ciphertext) tuple for prover/verifier tests."""
    msk_k = random_scalar()
    mpk_k = point_multiply(G2, msk_k)
    r = random_scalar()
    plaintext = 5
    C1 = point_multiply(G2, r)
    C2 = point_multiply(mpk_k, r) + point_multiply(G2, plaintext)
    return msk_k, mpk_k, C1, C2


def test_prove_and_verify_self():
    msk_k, mpk_k, C1, C2 = _setup_one_keyper()
    sigma = point_multiply(C1, msk_k)

    tp = Transcript("test:label:1")
    e, z = prove_decryption_share(tp, C1, C2, mpk_k, sigma, msk_k, keyper_index=1)

    tv = Transcript("test:label:1")
    assert verify_decryption_share(tv, C1, C2, mpk_k, sigma, e, z, keyper_index=1)


def test_make_decryption_share_helper():
    msk_k, mpk_k, C1, C2 = _setup_one_keyper()
    sigma_bytes, (e, z) = make_decryption_share(
        C1, C2, mpk_k, msk_k, keyper_index=2,
        transcript_label="test:label:2",
    )

    sigma = g2_from_compressed(sigma_bytes)
    tv = Transcript("test:label:2")
    assert verify_decryption_share(tv, C1, C2, mpk_k, sigma, e, z, keyper_index=2)


