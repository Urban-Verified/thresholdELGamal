# ----------------------------------------------------------------------
#  DLEQ encoding
# ----------------------------------------------------------------------

def test_dleq_roundtrip():
    e = random_scalar()
    z = random_scalar()
    b = encode_dleq(e, z)
    assert len(b) == DLEQ_BYTES == 64
    e2, z2 = decode_dleq(b)
    assert (e2, z2) == (e, z)


def test_dleq_decode_wrong_length():
    with pytest.raises(ValueError, match="64-byte"):
        decode_dleq(b"\x00" * 63)


