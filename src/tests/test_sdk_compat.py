def test_wr_attestation_verifier_accepts_oracle_signature():
    """End-to-end: oracle signs → verifier built from pkWR accepts."""
    from wr_oracle import issue_attestation
    wr_sk, wr_vk = schnorr_keygen()
    pk_wr = g1_to_compressed(wr_vk)
    election_id = b"\x01" * 32
    pseudonym = b"\x02" * 32
    voter_vk = b"\x03" * 48

    attest = issue_attestation(wr_sk, wr_vk, election_id, pseudonym, voter_vk)
    verify_wr = make_wr_attestation_verifier(pk_wr)
    assert verify_wr(election_id, pseudonym, voter_vk, attest)


def test_wr_attestation_verifier_rejects_tampered_attestation():
    from wr_oracle import issue_attestation
    wr_sk, wr_vk = schnorr_keygen()
    pk_wr = g1_to_compressed(wr_vk)
    election_id = b"\x01" * 32
    pseudonym = b"\x02" * 32
    voter_vk = b"\x03" * 48

    attest = bytearray(issue_attestation(wr_sk, wr_vk, election_id, pseudonym, voter_vk))
    attest[10] ^= 0xFF
    verify_wr = make_wr_attestation_verifier(pk_wr)
    assert not verify_wr(election_id, pseudonym, voter_vk, bytes(attest))


def test_wr_attestation_verifier_rejects_wrong_voter_vk():
    """A WR attestation issued for vk_A must not validate against vk_B."""
    from wr_oracle import issue_attestation
    wr_sk, wr_vk = schnorr_keygen()
    pk_wr = g1_to_compressed(wr_vk)
    election_id = b"\x01" * 32
    pseudonym = b"\x02" * 32

    attest = issue_attestation(wr_sk, wr_vk, election_id, pseudonym, b"\x03" * 48)
    verify_wr = make_wr_attestation_verifier(pk_wr)
    assert not verify_wr(election_id, pseudonym, b"\x04" * 48, attest)
