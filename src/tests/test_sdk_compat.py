def _load_ballot_fixture() -> dict:
    return json.loads(_BALLOT_FIXTURE.read_text())


def _ballot_inputs():
    fix = _load_ballot_fixture()
    inp = fix["inputs"]
    return {
        "election_id": bytes.fromhex(inp["electionId"]),
        "pseudonym": bytes.fromhex(inp["pseudonym"]),
        "sk": int(inp["sk"], 16),
        "k": int(inp["k"], 16),
        "mpk_secret": int(inp["mpk_secret"], 16),
        "mpk_bytes": bytes.fromhex(inp["mpk"]),
        "vk_bytes": bytes.fromhex(inp["vk"]),
        "votes": [int(v) for v in inp["votes"]],
        "rs": [int(r, 16) for r in inp["randomness"]],
        "range_w": [int(w, 16) for w in inp["range_proof_w"]],
        "range_sims": [
            [None if s is None else (int(s["e"], 16), int(s["z"], 16)) for s in row]
            for row in inp["range_proof_sims"]
        ],
        "budget_w": int(inp["budget_proof_w"], 16),
        "params": inp["params"],
        "out": fix["outputs"],
    }


def test_build_ballot_matches_sdk_byte_for_byte():
    """Pinned (sk, k, mpk-msk, r_j, OR commits) → identical SDK ballot bytes.

    This is the cross-impl gold for the full voter pipeline: ciphertexts,
    1611-byte zkProof, canonical preimage, and 80-byte voterSignature must
    all match what shutter-voting-sdk's buildBallot produced.
    """
    f = _ballot_inputs()
    mpk = point_multiply(G2, f["mpk_secret"])
    assert g2_to_compressed(mpk) == f["mpk_bytes"]

    _, vk = schnorr_keygen(f["sk"])
    assert g1_to_compressed(vk) == f["vk_bytes"]

    result = build_ballot(
        mpk=mpk,
        election_id=f["election_id"], pseudonym=f["pseudonym"],
        sk=f["sk"], vk=vk, votes=f["votes"],
        num_candidates=f["params"]["numCandidates"], budget=f["params"]["budget"],
        rs=f["rs"], range_proof_w=f["range_w"], range_proof_sims=f["range_sims"],
        budget_proof_w=f["budget_w"], schnorr_k=f["k"],
    )

    expected_cts = [(bytes.fromhex(c1), bytes.fromhex(c2))
                    for c1, c2 in f["out"]["ciphertexts"]]
    assert result.ciphertexts == expected_cts
    assert result.zk_proof == bytes.fromhex(f["out"]["zkProof"])
    assert result.canonical_preimage == bytes.fromhex(f["out"]["canonical_preimage"])
    assert result.voter_signature == bytes.fromhex(f["out"]["voterSignature"])


def test_verify_ballot_accepts_sdk_ballot():
    f = _ballot_inputs()
    mpk = point_multiply(G2, f["mpk_secret"])
    ok, reason = verify_ballot(
        mpk=mpk,
        election_id=f["election_id"], pseudonym=f["pseudonym"],
        vk_bytes=f["vk_bytes"],
        ciphertext_bytes=[(bytes.fromhex(c1), bytes.fromhex(c2))
                          for c1, c2 in f["out"]["ciphertexts"]],
        zk_proof=bytes.fromhex(f["out"]["zkProof"]),
        voter_signature=bytes.fromhex(f["out"]["voterSignature"]),
        wr_attestation=b"",
        num_candidates=f["params"]["numCandidates"],
        budget=f["params"]["budget"],
        verify_wr=lambda *a: True,
    )
    assert ok, reason


def test_verify_ballot_rejects_tampered_ciphertext():
    f = _ballot_inputs()
    mpk = point_multiply(G2, f["mpk_secret"])
    # Replace ciphertext[0].c1 with a fresh point — proof transcript breaks.
    cts = [(bytes.fromhex(c1), bytes.fromhex(c2))
           for c1, c2 in f["out"]["ciphertexts"]]
    other = g2_to_compressed(point_multiply(G2, random_scalar()))
    cts[0] = (other, cts[0][1])
    ok, reason = verify_ballot(
        mpk=mpk,
        election_id=f["election_id"], pseudonym=f["pseudonym"],
        vk_bytes=f["vk_bytes"],
        ciphertext_bytes=cts,
        zk_proof=bytes.fromhex(f["out"]["zkProof"]),
        voter_signature=bytes.fromhex(f["out"]["voterSignature"]),
        wr_attestation=b"",
        num_candidates=f["params"]["numCandidates"],
        budget=f["params"]["budget"],
        verify_wr=lambda *a: True,
    )
    assert not ok
    assert reason is not None and ("range proof" in reason or "signature" in reason)


def test_verify_ballot_rejects_when_wr_attestation_fails():
    f = _ballot_inputs()
    mpk = point_multiply(G2, f["mpk_secret"])
    ok, reason = verify_ballot(
        mpk=mpk,
        election_id=f["election_id"], pseudonym=f["pseudonym"],
        vk_bytes=f["vk_bytes"],
        ciphertext_bytes=[(bytes.fromhex(c1), bytes.fromhex(c2))
                          for c1, c2 in f["out"]["ciphertexts"]],
        zk_proof=bytes.fromhex(f["out"]["zkProof"]),
        voter_signature=bytes.fromhex(f["out"]["voterSignature"]),
        wr_attestation=b"\x00",
        num_candidates=f["params"]["numCandidates"],
        budget=f["params"]["budget"],
        verify_wr=lambda *a: False,    # always rejects
    )
    assert not ok
    assert reason == "wrAttestation verification failed"


