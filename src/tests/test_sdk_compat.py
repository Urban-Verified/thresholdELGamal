def _load_schnorr_fixture() -> dict:
    return json.loads(_SCHNORR_FIXTURE.read_text())


def test_schnorr_keygen_matches_sdk():
    fix = _load_schnorr_fixture()["inputs"]
    sk_in = int(fix["sk"], 16)
    sk_out, vk = schnorr_keygen(sk_in)
    assert sk_out == sk_in
    assert g1_to_compressed(vk) == bytes.fromhex(fix["vk"])


def test_schnorr_sign_matches_sdk_byte_for_byte():
    """Pinned (sk, k, msg) → must produce identical (R, s) bytes."""
    fix = _load_schnorr_fixture()["inputs"]
    sk = int(fix["sk"], 16)
    k = int(fix["k"], 16)
    msg = bytes.fromhex(fix["message"])
    _, vk = schnorr_keygen(sk)
    R, s = schnorr_sign(sk, vk, msg, k=k)
    assert g1_to_compressed(R) == bytes.fromhex(fix["R"])
    assert s == int(fix["s"], 16)
    assert encode_schnorr(R, s) == bytes.fromhex(fix["sig_encoded"])


def test_schnorr_verify_accepts_sdk_signature():
    fix = _load_schnorr_fixture()["inputs"]
    vk = g1_from_compressed(bytes.fromhex(fix["vk"]))
    msg = bytes.fromhex(fix["message"])
    R, s = decode_schnorr(bytes.fromhex(fix["sig_encoded"]))
    assert schnorr_verify(vk, msg, R, s)


def test_schnorr_tampered_message_rejected():
    fix = _load_schnorr_fixture()["inputs"]
    vk = g1_from_compressed(bytes.fromhex(fix["vk"]))
    msg = bytes.fromhex(fix["message"])
    R, s = decode_schnorr(bytes.fromhex(fix["sig_encoded"]))
    assert not schnorr_verify(vk, msg + b"\x00", R, s)


def test_schnorr_tampered_s_rejected():
    fix = _load_schnorr_fixture()["inputs"]
    vk = g1_from_compressed(bytes.fromhex(fix["vk"]))
    msg = bytes.fromhex(fix["message"])
    R, s = decode_schnorr(bytes.fromhex(fix["sig_encoded"]))
    assert not schnorr_verify(vk, msg, R, (s + 1) % (1 << 255))


